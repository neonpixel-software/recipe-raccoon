        "Sync stopped. Close Recipe Raccoon completely and open it again. If it keeps happening, copy the error details and report it.",
        "Copy Error Details",
    ]

    /// Translated, but the same word in some language ("System" in German), so the check
    /// above can't tell them from a missing entry.
    private let keysSameInSomeLanguage = ["System"]

    /// A missing entry falls back to the English key, and every key here differs from its
    /// translation in all four languages, so equality means the entry is missing.
    func testEverySettingsStringIsTranslated() {
        for key in keys {
            for languageCode in ["es", "fr", "de", "nl"] {
                let translated = LocalizationTestHelper.translatedString(key, languageCode: languageCode)
                XCTAssertNotNil(translated, "\(key) in \(languageCode)")
                XCTAssertNotEqual(translated, key, "\(key) in \(languageCode)")
            }
        }
    }

    func testSettingsStringsThatCanMatchEnglishHaveEntries() {
        for key in keysSameInSomeLanguage {
            for languageCode in ["es", "fr", "de", "nl"] {
                XCTAssertTrue(LocalizationTestHelper.hasEntry(key, languageCode: languageCode), "\(key) in \(languageCode)")
            }
        }
    }

    /// The "Last updated" row interpolates a formatted date, so its catalog key is generated by
    /// SwiftUI. Read the key the view actually builds instead of trusting the literal above.
    @MainActor
    func testLastUpdatedResolvesToItsCatalogKey() throws {
        let key = SettingsView.lastUpdatedText(Date())
        let keyString = try XCTUnwrap(Mirror(reflecting: key).children.first { $0.label == "key" }?.value as? String)

        XCTAssertEqual(keyString, "Last updated %@")
        XCTAssertEqual(LocalizationTestHelper.translatedString(keyString, languageCode: "de"), "Zuletzt aktualisiert: %@")
    }

    @MainActor
    func testLastSyncedResolvesToItsCatalogKey() throws {
        let key = SettingsView.lastSyncedText(Date())
        let keyString = try XCTUnwrap(Mirror(reflecting: key).children.first { $0.label == "key" }?.value as? String)

        XCTAssertEqual(keyString, "Last synced %@")
        XCTAssertEqual(LocalizationTestHelper.translatedString(keyString, languageCode: "de"), "Zuletzt synchronisiert: %@")
    }

    func testSpotCheckGermanStorageLabels() {
        XCTAssertEqual(LocalizationTestHelper.translatedString("On This Device", languageCode: "de"), "Auf diesem Gerät")
        XCTAssertEqual(LocalizationTestHelper.translatedString("Settings", languageCode: "de"), "Einstellungen")
    }
}

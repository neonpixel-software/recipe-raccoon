@testable import RecipeRaccoon
import SwiftUI
import XCTest

/// Every string the settings screen shows (Phase 4.1) must have a catalog entry in each
/// translated language. The translations themselves still need the fluent-speaker pass (#65).
final class LocalizedSettingsStringsTests: XCTestCase {
    private let keys = [
        "Settings",
        "Done",
        "Storage",
        "Store Recipes",
        "On This Device",
        "Moving your recipes…",
        "With iCloud, your recipes sync to your other devices signed in to the same account. Switching back to this device keeps a copy of every recipe here and stops syncing.",
        "iCloud sync isn't available in this build.",
        "Sign in to iCloud on this device to sync your recipes.",
        "iCloud is restricted on this device, so recipes can't sync.",
        "iCloud is temporarily unavailable. Try again in a moment.",
        "Couldn't reach iCloud. Check your connection and try again.",
        "Couldn't change where recipes are stored. Try again.",
        // Phase 10.2: ingredient densities.
        "Ingredient Densities",
        "Refresh Now",
        "Last updated %@",
        "Not downloaded yet",
        "Ingredient densities are up to date.",
        "Ingredient densities updated.",
        "Couldn't refresh ingredient densities. Check your connection and try again.",
        "Recipe Raccoon uses ingredient densities to convert between volume and weight. It checks for updates once a day.",
        "Ingredient densities aren't available in this build.",
        "The ingredient density service didn't accept this version of Recipe Raccoon. Update the app and try again.",
        "The ingredient density service isn't responding properly right now. Try again later.",
        "Couldn't save ingredient densities on this device. Try again.",
        // The cup and spoon size setting.
        "Measurements",
        "Cups and Spoons",
        "US Customary",
        "Metric",
        "Used to show ingredients by weight. A US cup is 237 ml; a metric cup is 250 ml.",
        // Theme and language.
        "Appearance",
        "Theme",
        "Light",
        "Dark",
        "Language",
        "Open Settings",
        "Open System Settings",
        "Recipe Raccoon uses your Mac's language. To choose another one for this app only, add Recipe Raccoon under Applications in Language & Region.",
        "Recipe Raccoon uses your device's language. To use another one for this app only, choose it under Language in Settings. If it isn't listed, add it to your device's languages first.",
        // The iCloud sync status (#208).
        "Last synced %@",
        "Waiting for the first sync…",
        "iCloud storage is full, so recipes can't sync. Free up space in iCloud, or switch to “On This Device”.",
        "Not signed in to iCloud, so recipes can't sync. Sign in on this device, or switch to “On This Device”.",
